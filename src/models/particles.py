"""Частицы фейерверка: ракета и искры."""

DRAG = 0.98              # каждый кадр искра теряет 2 % скорости (воздух)
FADE_FRAMES = 30         # за сколько кадров до смерти искра начинает гаснуть


class Particle:
    """Точка, которая летит со скоростью (dx, dy) и падает под гравитацией."""

    def __init__(self, x, y, dx, dy, color):
        """Создать частицу в точке (x, y) со скоростью (dx, dy) за кадр."""
        self.x = x
        self.y = y
        self.dx = dx
        self.dy = dy
        self.color = color

    def move(self, gravity):
        """Сдвинуть частицу на один кадр.

        Ось y на экране направлена вниз, поэтому гравитация каждый кадр
        прибавляется к dy: летящая вверх частица тормозит, а падающая
        разгоняется. Так получается движение по параболе.
        """
        self.dy += gravity
        self.x += self.dx
        self.y += self.dy


class Rocket(Particle):
    """Ракета: летит вверх и взрывается в самой высокой точке."""

    def is_at_top(self):
        """Перестала ли ракета подниматься (значит, пора взрываться)."""
        return self.dy >= 0


class Spark(Particle):
    """Искра взрыва: живёт ограниченное число кадров."""

    def __init__(self, x, y, dx, dy, color, life):
        """Создать искру, которая проживёт life кадров."""
        super().__init__(x, y, dx, dy, color)
        self.life = life         # сколько кадров осталось жить

    def move(self, gravity):
        """Сдвинуть искру на кадр и уменьшить оставшуюся жизнь."""
        # Сопротивление воздуха: скорость понемногу падает, поэтому искры
        # сначала быстро разлетаются, а потом медленно опускаются.
        self.dx *= DRAG
        self.dy *= DRAG
        super().move(gravity)
        self.life -= 1

    def is_alive(self):
        """Жива ли ещё искра."""
        return self.life > 0

    @property
    def brightness(self):
        """Яркость искры от 1 (горит) до 0 (погасла).

        Искра горит в полную силу, а за последние FADE_FRAMES кадров
        жизни плавно гаснет: например, за 15 кадров до конца — 15 / 30.
        """
        return min(1, self.life / FADE_FRAMES)
